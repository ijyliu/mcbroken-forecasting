def save_description_html_aws(client, bucket, description_html, filename):
    import boto3
    # Save description as HTML to temporary Lambda storage
    html_output = '/tmp/' + filename + '.html'
    with open(html_output, 'w') as f:
        f.write(description_html)

    # Upload HTML to S3 and make it publicly accessible
    client.upload_file(html_output, bucket, filename, ExtraArgs={'ContentType': 'text/html', 'ACL': 'public-read'})

    # Return the S3 link
    return {
        'statusCode': 200,
        'body': f"Forecast saved to: https://{bucket}.s3.amazonaws.com/{filename}"
    }

