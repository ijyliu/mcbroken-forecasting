def get_api_key_local():
    """
    This function retrieves the Gemini API key from ~/Documents/Gemini/mcbroken-forecasting.txt.

    Returns:
    - str: The Gemini API key
    """
    # Define the path to the file containing the API key
    api_key_path = os.path.expanduser("~/Documents/Gemini/mcbroken-forecasting.txt")
    
    # Open the file and read the API key
    with open(api_key_path, 'r') as file:
        api_key = file.read().strip()  # Remove any leading/trailing whitespace
    
    return api_key

def get_api_key_aws():
    """
    Load the Gemini API key from a secure location in AWS.
    
    Returns:
    - str: The Gemini API key
    """
    import boto3
    # S3 details
    s3 = boto3.client('s3')
    bucket = 'mcbroken-forecasting-api-keys'  # S3 bucket name for storing API keys
    key = 'mcbroken-forecasting.txt'  # File name in S3

    # Load data from S3
    obj = s3.get_object(Bucket=bucket, Key=key)
    api_key = obj['Body'].read().decode('utf-8').strip()  # Read and decode the API key

    return api_key

